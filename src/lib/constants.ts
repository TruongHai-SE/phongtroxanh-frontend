export function calculateDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

function stripVietnameseAccents(str: string): string {
  return str
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D");
}

function scoreLandmarkMatch(lm: LandmarkLocation, rawQuery: string): number {
  const rawLower = rawQuery.trim().toLowerCase();
  if (!rawLower) return 0;

  // Strip common prefix words ONLY if there are other words left
  const stripped = rawLower
    .replace(/\b(trường|đại học|đh|cao đẳng|cđ|học viện|hv|thành phố hồ chí minh|tp\.?\s*hcm|tphcm|gần|khu vực|quanh|trong)\b/giu, " ")
    .replace(/\s+/g, " ")
    .trim();
  const effectiveQuery = stripped.length >= 2 ? stripped : rawLower;
  const queryNoAccent = stripVietnameseAccents(effectiveQuery);
  const queryTokens = effectiveQuery.split(/\s+/).filter(Boolean);
  const queryTokensNoAccent = queryNoAccent.split(/\s+/).filter(Boolean);

  // 1. Exact keyword or acronym match (highest priority: e.g. "iu" === "iu", never matches "iuh")
  for (const kw of lm.keywords) {
    const kwLower = kw.toLowerCase();
    const kwNoAccent = stripVietnameseAccents(kwLower);
    if (kwLower === effectiveQuery || kwLower === rawLower || kwNoAccent === queryNoAccent) {
      return 100;
    }
    // Single-token acronym match (e.g. user typed "trường iu" or "đh iu")
    if (kwLower.length <= 6 && !kwLower.includes(" ") && queryTokens.includes(kwLower)) {
      return 90;
    }
  }

  // 2. Full phrase contained inside landmark name, shortName, or multi-word keyword (whole-word aware)
  const hayFull = `${lm.name} ${lm.shortName} ${lm.keywords.join(" | ")}`.toLowerCase();
  const hayNoAccent = stripVietnameseAccents(hayFull);

  if (effectiveQuery.length >= 3) {
    // Check if all query tokens exist as whole words or prefixes in the landmark's text
    const hayWords = hayFull.split(/[\s,()|-]+/).filter(Boolean);
    const hayWordsNoAccent = hayNoAccent.split(/[\s,()|-]+/).filter(Boolean);

    const allTokensMatchExactWord = queryTokens.every((qt) =>
      hayWords.some((hw) => hw === qt || (qt.length >= 3 && hw.startsWith(qt)))
    );
    if (allTokensMatchExactWord) {
      // Bonus if the contiguous phrase appears
      return hayFull.includes(effectiveQuery) ? 85 : 75;
    }

    const allTokensMatchNoAccent = queryTokensNoAccent.every((qt) =>
      hayWordsNoAccent.some((hw) => hw === qt || (qt.length >= 3 && hw.startsWith(qt)))
    );
    if (allTokensMatchNoAccent) {
      return hayNoAccent.includes(queryNoAccent) ? 70 : 60;
    }
  }

  return 0;
}

export function resolveLandmarkFromQuery(raw?: string): LandmarkLocation | undefined {
  if (!raw || raw.trim().length < 2) return undefined;
  let best: LandmarkLocation | undefined;
  let bestScore = 0;

  for (const lm of HCMC_LANDMARKS) {
    const score = scoreLandmarkMatch(lm, raw);
    if (score > bestScore) {
      bestScore = score;
      best = lm;
    }
  }
  return bestScore >= 60 ? best : undefined;
}

export function searchLocalLandmarks(raw?: string, limit = 7): LandmarkLocation[] {
  const trimmed = (raw || "").trim();
  if (!trimmed) {
    return HCMC_LANDMARKS.slice(0, limit);
  }

  const scored = HCMC_LANDMARKS.map((lm) => ({
    lm,
    score: scoreLandmarkMatch(lm, trimmed),
  }))
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score);

  return scored.slice(0, limit).map((item) => item.lm);
}

const VOWELS_OR_ACRONYMS_RE =
  /(?:[aeiouyăâêôơưáàảãạắằẳẵặấầẩẫậéèẻẽẹếềểễệíìỉĩịóòỏõọốồổỗộớờởỡợúùủũụứừửữựýỳỷỹỵ]|\b(?:đh|cđ|thpt|cty|fpt|vng|cmc|vnpt|kms|rmit|kpmg|pwc|dhl|cgv|bhd|acb|shb|tcb|mbb|vpb|bidv)\b)/iu;

export function validateSchoolOrCompany(raw: string): string | null {
  const cleaned = (raw || "").trim().replace(/\s+/g, " ");
  if (!cleaned) {
    return "Vui lòng nhập tên trường học hoặc nơi làm việc";
  }
  if (cleaned.length < 2 || cleaned.length > 100) {
    return "Tên trường học hoặc nơi làm việc cần từ 2 đến 100 ký tự";
  }
  if (!/^[\p{L}\d\s.,\-&()/+'']+$/u.test(cleaned) || cleaned.replace(/[^\p{L}]/gu, "").length < 2) {
    return "Tên trường học hoặc nơi làm việc chỉ gồm chữ cái, số và dấu câu cơ bản";
  }
  if (
    /(.)\1{3,}/iu.test(cleaned) ||
    /^(.{2,3})\1+$/iu.test(cleaned) ||
    /(asdf|qwer|zxcv|hjkl|bnm)/iu.test(cleaned) ||
    !VOWELS_OR_ACRONYMS_RE.test(cleaned)
  ) {
    return "Vui lòng nhập tên trường học hoặc nơi làm việc thực tế (ví dụ: ĐH FPT, Công ty VNG)";
  }
  return null;
}

