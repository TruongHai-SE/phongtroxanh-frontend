export function expandPlaceQueryForMap(raw: string): string {
  const trimmed = raw.trim();
  if (!trimmed) return "";
  const lower = trimmed.toLowerCase();
  if (SCHOOL_ACRONYM_MAP[lower]) {
    return SCHOOL_ACRONYM_MAP[lower];
  }
  return trimmed
    .replace(/\s*\([A-Za-z0-9\s-]+\)/g, "")
    .replace(/\bđh\b/giu, "Trường Đại học")
    .replace(/\bcđ\b/giu, "Trường Cao đẳng")
    .replace(/\bhv\b/giu, "Học viện")
    .replace(/\bktx\b/giu, "Ký túc xá")
    .replace(/\bnvhsv\b/giu, "Nhà Văn hóa Sinh viên")
    .replace(/\bđhqg\b/giu, "Đại học Quốc gia")
    .replace(/\bcs\s*1\b/giu, "Cơ sở 1")
    .replace(/\bcs\s*2\b/giu, "Cơ sở 2")
    .replace(/\bcơ sở\s+ii\b/giu, "Cơ sở 2")
    .replace(/\bcơ sở\s+i\b/giu, "Cơ sở 1")
    .replace(/\btp\.?\s*hcm\b/giu, "Thành phố Hồ Chí Minh")
    .replace(/\btphcm\b/giu, "Thành phố Hồ Chí Minh")
    .replace(/\s+/g, " ")
    .trim();
}

